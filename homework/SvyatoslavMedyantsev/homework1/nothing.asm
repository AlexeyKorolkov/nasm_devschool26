global _start           ; экспортируем метку _start чтобы её увидел компоновщик ld

section .text           ; секция исполняемого кода

_start:                 ; точка входа - с этого адреса ядро начинает выполнение
    mov rax, 60         ; в rax - номер системного вызова: 60 = exit
    mov rdi, 0          ; в rdi - первый аргумент exit: код возврата 0 (успех)
    syscall             ; передаём управление ядру - процесс завершается
